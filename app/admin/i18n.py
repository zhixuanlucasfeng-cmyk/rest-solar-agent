def get_language(request: Request) -> str:
    language = request.cookies.get("admin_lang")
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translate(language: str, key: str, **values) -> str:
    chosen = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    return TRANSLATIONS[chosen][key].format(**values)


def admin_context(request: Request) -> dict:
    language = get_language(request)
    return {
        "lang": language,
        "supported_languages": SUPPORTED_LANGUAGES,
        "t": lambda key, **values: translate(language, key, **values),
    }
